import { test, expect } from '@playwright/test';
test('小屋：生成新版本、体检、导出、展出并回退', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: '我的灵感' })).toBeVisible();
  await expect(page.getByTestId('model-viewer').locator('canvas')).toBeVisible();
  await page.getByRole('button', { name: '开始新作品' }).click();
  await page.getByLabel('我的造物想法').fill('一只圆滚滚的小兔，高80毫米');
  await page.getByRole('button', { name: '生成模型', exact: true }).click();
  await expect(page.getByText('呀哈！新版本已经放进作品柜。')).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: '关闭提示' }).click();
  await page.getByLabel('高度数值').fill('90');
  await page.getByRole('button', { name: '保存新版本' }).click();
  await expect(page.getByRole('heading', { name: '版本 02' })).toBeVisible();
  await page.getByRole('button', { name: '去模型体检', exact: true }).click();
  await expect(page.getByText('基础体检完成 ✓')).toBeVisible();
  await page.getByRole('button', { name: '去打印准备台 →' }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '3MF', exact: true }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.3mf$/);
  await page.getByLabel('四周留边（mm）').fill('20');
  await expect(page.getByRole('button', { name: '交给 Bambu Studio' })).toBeDisabled();
  await page.getByRole('navigation').getByRole('button', { name: '乌萨奇展厅' }).click();
  const story = `我和爸爸一起做的第一只小兔。${Date.now()}`;
  await page.getByLabel('作品故事').fill(story);
  await page.getByRole('button', { name: '摆进我的展厅' }).click();
  await expect(page.getByRole('article').getByText(story).first()).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: '作品柜', exact: true }).click();
  await page.getByRole('button', { name: '回到这一版' }).first().click();
  await expect(page.getByText('回到了这个形状，原来的版本也保留着。')).toBeVisible();
  expect(errors).toEqual([]);
});
